@pytest.fixture
def database_url():
    raw_url = os.environ.get("TEST_DATABASE_URL")
    if not raw_url:
        pytest.skip("Set TEST_DATABASE_URL to run PostgreSQL integration tests")
    base_url = make_url(raw_url)
    if base_url.drivername != "postgresql+psycopg":
        pytest.fail("Integration tests require PostgreSQL with psycopg")
    schema = f"physics_test_{uuid4().hex}"
    admin = create_engine(base_url)
    try:
        with admin.begin() as connection:
            connection.execute(CreateSchema(schema))
    except SQLAlchemyError:
        admin.dispose()
        pytest.fail(
            "PostgreSQL test setup unavailable; check TEST_DATABASE_URL (value hidden).",
            pytrace=False,
        )
    isolated_url = base_url.update_query_dict({"options": f"-csearch_path={schema}"})
    engine = create_engine(isolated_url)
    try:
        config = Config(str(API_ROOT / "alembic.ini"))
        config.set_main_option("script_location", str(API_ROOT / "migrations"))
        with engine.begin() as connection:
            config.attributes["connection"] = connection
            command.upgrade(config, "head")
        # URL repr masks credentials in pytest fixture diagnostics.
        yield isolated_url
    finally:
        engine.dispose()
        # Only the schema generated by this fixture is ever removed.
        with admin.begin() as connection:
            connection.execute(DropSchema(schema, cascade=True))
        admin.dispose()


