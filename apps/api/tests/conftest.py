@pytest.fixture
def pdf_factory():
    """Build small real PDFs whose text and page positions are known in advance."""

    def build(*pages: str) -> bytes:
        writer = PdfWriter()
        for text in pages:
            page = writer.add_blank_page(width=595, height=842)
            if not text:
                continue
            font = DictionaryObject(
                {
                    NameObject("/Type"): NameObject("/Font"),
                    NameObject("/Subtype"): NameObject("/Type1"),
                    NameObject("/BaseFont"): NameObject("/Helvetica"),
                }
            )
            page[NameObject("/Resources")] = DictionaryObject(
                {
                    NameObject("/Font"): DictionaryObject(
                        {NameObject("/F1"): writer._add_object(font)}
                    )
                }
            )
            commands = [b"BT /F1 12 Tf 40 780 Td 16 TL"]
            for index, line in enumerate(text.splitlines()):
                if index:
                    commands.append(b"T*")
                escaped = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
                commands.append(b"(" + escaped.encode("ascii") + b") Tj")
            commands.append(b"ET")
            stream = StreamObject()
            stream.set_data(b"\n".join(commands))
            page[NameObject("/Contents")] = writer._add_object(stream)
        output = BytesIO()
        writer.write(output)
        return output.getvalue()

    return build
